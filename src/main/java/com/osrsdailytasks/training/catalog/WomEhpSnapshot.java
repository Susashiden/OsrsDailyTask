	private static TrainingMethodDefinition row(
		EhpProfile profile,
		String skillId,
		long startXp,
		double ehpRate,
		double actualSkillRate,
		String description)
	{
		String methodId = "wom-"
			+ profile.name().toLowerCase(Locale.ENGLISH)
			+ "-"
			+ skillId.toLowerCase(Locale.ENGLISH).replace('_', '-')
			+ "-"
			+ startXp;
		return new TrainingMethodDefinition(
			methodId,
			profile,
			skillId,
			startXp,
			description,
			ehpRate,
			actualSkillRate,
			SOURCE,
			null);
	}
